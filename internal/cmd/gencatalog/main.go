// Command gencatalog writes events/catalog_gen.go: the EventType and Topic methods of every payload type and the
// catalogue that maps an event type to its topic and schema. It reads events/<topic>/<Event>.schema.json, so the
// directory a schema sits in is the topic its event is published on. Run it from the repository root (make
// generate does).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path"
	"sort"
	"strings"

	"github.com/osbe/contracts/internal/schema"
)

func main() {
	log.SetFlags(0)
	out := "events/catalog_gen.go"
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	src, err := generate()
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

type event struct{ name, topicDir, schema string }

func generate() ([]byte, error) {
	paths, err := schema.Paths(os.DirFS("."))
	if err != nil {
		return nil, err
	}
	var evs []event
	topics := map[string]bool{}
	for _, p := range paths {
		dir := path.Dir(p)
		topicDir, ok := strings.CutPrefix(dir, "events/")
		if !ok || strings.Contains(topicDir, "/") {
			continue
		}
		topics[topicDir] = true
		evs = append(evs, event{name: schema.Name(p), topicDir: topicDir, schema: p})
	}
	sort.Slice(evs, func(i, j int) bool { return evs[i].name < evs[j].name })
	topicDirs := make([]string, 0, len(topics))
	for t := range topics {
		topicDirs = append(topicDirs, t)
	}
	sort.Strings(topicDirs)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/cmd/gencatalog from events/*/*.schema.json; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package events\n\n")
	fmt.Fprintf(&b, "// Kafka topics, one per aggregate.\nconst (\n")
	for _, t := range topicDirs {
		fmt.Fprintf(&b, "\t%s = %q\n", topicConst(t), "hotl."+t)
	}
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// Topics lists every topic.\nvar Topics = []string{")
	for _, t := range topicDirs {
		fmt.Fprintf(&b, "%s, ", topicConst(t))
	}
	fmt.Fprintf(&b, "}\n\n")
	for _, e := range evs {
		fmt.Fprintf(&b, "// EventType returns %q.\nfunc (%s) EventType() string { return %q }\n\n", e.name, e.name, e.name)
		fmt.Fprintf(&b, "// Topic returns %s.\nfunc (%s) Topic() string { return %s }\n\n", topicConst(e.topicDir), e.name, topicConst(e.topicDir))
	}
	fmt.Fprintf(&b, "var catalog = map[string]spec{\n")
	for _, e := range evs {
		fmt.Fprintf(&b, "\t%q: {topic: %s, schema: %q, new: func() Payload { return new(%s) }},\n",
			e.name, topicConst(e.topicDir), e.schema, e.name)
	}
	fmt.Fprintf(&b, "}\n")
	return format.Source(b.Bytes())
}

func topicConst(dir string) string { return "Topic" + strings.ToUpper(dir[:1]) + dir[1:] }
